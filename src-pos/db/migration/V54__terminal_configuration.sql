CREATE TABLE TERMINALS (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    LEGACY_HOSTNAME VARCHAR(255),
    LEGACY_RESOURCE VARCHAR(255),
    ACTIVE_CASH VARCHAR(255),
    LOCATION_ID VARCHAR(255) NOT NULL DEFAULT '0'
);
CREATE UNIQUE INDEX TERMINALS_LEGACY_RESOURCE_INX ON TERMINALS(LEGACY_RESOURCE);

CREATE TABLE TERMINAL_SETTINGS (
    TERMINAL_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    PRINTER VARCHAR(255) NOT NULL DEFAULT 'screen',
    PRINTER_2 VARCHAR(255) NOT NULL DEFAULT 'Not defined',
    PRINTER_3 VARCHAR(255) NOT NULL DEFAULT 'Not defined',
    PRINTER_NAME VARCHAR(255) NOT NULL DEFAULT '(Default)',
    DISPLAY_DEVICE VARCHAR(255) NOT NULL DEFAULT 'screen',
    SCANNER VARCHAR(255) NOT NULL DEFAULT 'Not defined',
    SCREEN_MODE VARCHAR(32) NOT NULL DEFAULT 'window',
    TICKETS_BAG VARCHAR(32) NOT NULL DEFAULT 'standard',
    MENU_STATE VARCHAR(16) NOT NULL DEFAULT '',
    UNIQUE_INSTANCE SMALLINT NOT NULL DEFAULT 0,
    LANGUAGE VARCHAR(16) NOT NULL DEFAULT 'ca',
    COUNTRY VARCHAR(16) NOT NULL DEFAULT 'ES',
    VARIANT VARCHAR(32) NOT NULL DEFAULT '',
    FORMAT_INTEGER VARCHAR(128) NOT NULL DEFAULT '',
    FORMAT_DOUBLE VARCHAR(128) NOT NULL DEFAULT '',
    FORMAT_CURRENCY VARCHAR(128) NOT NULL DEFAULT '',
    FORMAT_PERCENT VARCHAR(128) NOT NULL DEFAULT '',
    FORMAT_DATE VARCHAR(128) NOT NULL DEFAULT '',
    FORMAT_TIME VARCHAR(128) NOT NULL DEFAULT '',
    FORMAT_DATETIME VARCHAR(128) NOT NULL DEFAULT '',
    PAPER_RECEIPT_X VARCHAR(32) NOT NULL DEFAULT '10',
    PAPER_RECEIPT_Y VARCHAR(32) NOT NULL DEFAULT '287',
    PAPER_RECEIPT_WIDTH VARCHAR(32) NOT NULL DEFAULT '190',
    PAPER_RECEIPT_HEIGHT VARCHAR(32) NOT NULL DEFAULT '546',
    PAPER_RECEIPT_MEDIA VARCHAR(128) NOT NULL DEFAULT 'A4',
    PAPER_STANDARD_X VARCHAR(32) NOT NULL DEFAULT '72',
    PAPER_STANDARD_Y VARCHAR(32) NOT NULL DEFAULT '72',
    PAPER_STANDARD_WIDTH VARCHAR(32) NOT NULL DEFAULT '451',
    PAPER_STANDARD_HEIGHT VARCHAR(32) NOT NULL DEFAULT '698',
    PAPER_STANDARD_MEDIA VARCHAR(128) NOT NULL DEFAULT 'A4',
    UPDATE_CHECK SMALLINT NOT NULL DEFAULT 1,
    UPDATE_URL VARCHAR(512) NOT NULL DEFAULT 'https://api.github.com/repos/albertpastrana/retail-pos/releases/latest',
    CONSTRAINT TERMINAL_SETTINGS_FK FOREIGN KEY (TERMINAL_ID) REFERENCES TERMINALS(ID)
);

CREATE TABLE BACKUP_POLICY (
    ID VARCHAR(1) NOT NULL PRIMARY KEY,
    ENABLED SMALLINT NOT NULL DEFAULT 0,
    HOUR_OF_DAY SMALLINT NOT NULL DEFAULT 2,
    RETENTION_DAYS INTEGER NOT NULL DEFAULT 30,
    TERMINAL_ID VARCHAR(36),
    LAST_DATE VARCHAR(8),
    LEASE_OWNER VARCHAR(36),
    LEASE_UNTIL TIMESTAMP,
    CONSTRAINT BACKUP_POLICY_TERMINAL_FK FOREIGN KEY (TERMINAL_ID) REFERENCES TERMINALS(ID)
);
